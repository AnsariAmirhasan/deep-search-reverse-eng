"""Pydantic data models for the reverse-engineering deep-search agent."""

from typing import List, Optional, Literal, Dict, Any
from pydantic import BaseModel, Field


class ResearchPlanItem(BaseModel):
    """An individual dimension of investigation in the reverse-engineering plan."""
    id: str = Field(description="Unique short ID for the plan item, e.g. 'dim-1'")
    title: str = Field(description="Title of the research dimension, e.g. 'API & Protocol Analysis'")
    focus_area: str = Field(
        description="Core focus: 'architecture', 'api_protocols', 'workflows_logic', 'data_storage', 'security', or 'reconstruction'"
    )
    description: str = Field(description="Detailed explanation of what needs to be reverse engineered in this step")
    target_queries: List[str] = Field(description="Targeted search queries to uncover internal mechanics")


class ResearchPlan(BaseModel):
    """The complete structured reverse-engineering plan (reviewed by user in HITL)."""
    tool_name: str = Field(description="Name or URL of the tool to reverse engineer")
    summary: str = Field(description="High-level overview of the target system and objectives")
    items: List[ResearchPlanItem] = Field(description="List of ordered investigation dimensions")


class SearchSource(BaseModel):
    """A referenced web source or engineering document."""
    id: str
    title: str
    url: str
    domain: str
    snippet: Optional[str] = None


class Feedback(BaseModel):
    """Evaluator agent reflection feedback."""
    grade: Literal["pass", "fail"] = Field(
        description="'pass' if findings are sufficient for full reverse engineering, 'fail' if gaps remain"
    )
    comment: str = Field(description="Evaluation explanation highlighting strengths and missing technical gaps")
    follow_up_queries: List[str] = Field(
        default_factory=list,
        description="Targeted follow-up search queries to fix technical gaps if grade is 'fail'"
    )


class ResearchFindings(BaseModel):
    """Accumulated knowledge gathered during iterative research."""
    tool_name: str
    iterations_run: int = 0
    raw_findings: List[str] = Field(default_factory=list)
    sources: Dict[str, SearchSource] = Field(default_factory=dict)
    identified_tech_stack: List[str] = Field(default_factory=list)
    identified_endpoints: List[Dict[str, Any]] = Field(default_factory=list)
    identified_components: List[str] = Field(default_factory=list)


class ReverseEngineeringDossier(BaseModel):
    """Final comprehensive report generated by the Synthesizer."""
    tool_name: str
    executive_summary: str
    tech_stack: Dict[str, List[str]]
    architecture_overview: str
    mermaid_diagram: str
    api_specifications: str
    data_models_and_storage: str
    workflow_and_algorithms: str
    reconstruction_blueprint: str
    sources_cited: List[Dict[str, str]]
